async def ensure_seed(db):
    if await db.pages.count_documents({}) == 0:
        for page in PAGES_SEED:
            doc = {**page, "id": str(uuid.uuid4()), "published": True,
                   "created_at": datetime.now(timezone.utc).isoformat(),
                   "updated_at": datetime.now(timezone.utc).isoformat()}
            await db.pages.insert_one(doc)
    if await db.settings.count_documents({"_key": "site"}) == 0:
        await db.settings.insert_one(SETTINGS_SEED)
